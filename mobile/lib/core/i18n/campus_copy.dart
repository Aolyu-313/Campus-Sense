  String codeLabel(String code) {
    final normalized = code.toUpperCase();
    return codeLabels[normalized] ??
        _englishCodeLabels[normalized] ??
        normalized
            .split('_')
            .map(
              (word) => word.isEmpty
                  ? word
                  : word[0] + word.substring(1).toLowerCase(),
            )
            .join(' ');
  }

